        private TextMeshProUGUI TableBlock(string name)
        {
            TextMeshProUGUI text = _ui.Text(name, _tableBox, string.Empty, TableMaxFont, _ui.Theme.TextPrimary,
                TextAlignmentOptions.TopLeft);
            text.richText = true;
            text.enableWordWrapping = false;
            text.overflowMode = TextOverflowModes.Overflow;
            RectTransform rect = text.rectTransform;
            rect.anchorMin = rect.anchorMax = new Vector2(0f, 1f);
            rect.pivot = new Vector2(0f, 1f);
            return text;
        }

        /// <summary>Schedules the card for <paramref name="item"/>, placed to the right of <paramref name="anchor"/>.</summary>
        public void Request(LibraryItemView item, RectTransform anchor)
        {
            if (item == null)
            {
                return;
            }

            bool alreadyShown = gameObject.activeSelf && _built && Time.unscaledTime >= _showAt;
            _source = item;
            _anchor = anchor;
            _built = false;
            // Moving between rows while the card is up swaps it at once instead of waiting again.
            _showAt = Time.unscaledTime + (alreadyShown ? 0f : Delay);
            if (!alreadyShown)
            {
                _group.DOKill();
                _group.alpha = 0f;
            }

            gameObject.SetActive(true);
            transform.SetAsLastSibling();
        }

        /// <summary>Builds and shows the card for <paramref name="item"/> immediately (tests, keyboard focus).</summary>
        public void ShowNow(LibraryItemView item, RectTransform anchor)
        {
            Request(item, anchor);
            _showAt = Time.unscaledTime;
            Populate();
            _group.DOKill();
            _group.alpha = 1f;
        }

        /// <summary>Hides the card if it belongs to <paramref name="item"/> (or always when null).</summary>
        public void Release(LibraryItemView item)
        {
            if (item == null || item == _source)
            {
                _source = null;
                _built = false;
                _group.DOKill();
                gameObject.SetActive(false);
            }
        }

        /// <summary>Forgets cached truth tables (the library changed).</summary>
        public void ClearCache()
        {
            _tables.Clear();
            if (_source != null && gameObject.activeSelf)
            {
                Release(null);
            }
        }

        private void LateUpdate()
        {
            if (_source == null || !_source.gameObject.activeInHierarchy)
            {
                Release(null);
                return;
            }

            if (!_built && Time.unscaledTime >= _showAt)
            {
                Populate();
                if (_group.alpha < 1f)
                {
                    _group.DOFade(1f, 0.12f).SetUpdate(true);
                }
            }
        }

        private void Populate()
        {
            _built = true;
            LibraryEntrySpec spec = _source.Spec;
            ComponentRef component = spec.Request.Component;
            VisualTheme theme = _ui.Theme;
            CircuitDefinition definition = null;
            if (component.Kind == ComponentKind.Custom)
            {
                _workspace.Catalog.TryGetDefinition(component.Definition, out definition);
            }

            _title.text = spec.Title;
            bool showVersion = definition != null && _workspace.ShowGateVersions;
            _badgeBack.gameObject.SetActive(showVersion || component.Kind == ComponentKind.Primitive);
            _badge.text = showVersion ? "v" + definition.Version.ToString(CultureInfo.InvariantCulture)
                : component.Kind == ComponentKind.Primitive ? "built-in" : string.Empty;
            _badgeBack.GetComponent<LayoutElement>().preferredWidth = _badge.GetPreferredValues(_badge.text).x + 12f;

            _subtitle.text = definition != null
                ? (string.IsNullOrWhiteSpace(definition.Category) ? LibraryPanel.UncategorizedLabel : definition.Category.Trim())
                : component.Kind == ComponentKind.Primitive ? "Logic primitive"
                : component.IsBoundary || component.Kind == ComponentKind.Constant ? "Circuit utility"
                : component.Kind == ComponentKind.Display ? "Display"
                : component.Kind == ComponentKind.Clock ? "Timing"
                : "Bus wiring";

            DrawDiagram(component, spec);

            string description = definition != null && !string.IsNullOrWhiteSpace(definition.Description)
                ? definition.Description.Trim()
                : !string.IsNullOrEmpty(spec.Description) ? spec.Description : spec.Detail;
            _description.text = description ?? string.Empty;
            _description.gameObject.SetActive(!string.IsNullOrEmpty(description) && !spec.ShowDetail ||
                definition != null && !string.IsNullOrWhiteSpace(definition.Description));

            string dot = "  <color=#" + ColorUtility.ToHtmlStringRGB(theme.PanelBorder) + ">·</color>  ";
            _builder.Clear();
            _builder.Append(spec.Inputs).Append(spec.Inputs == 1 ? " input" : " inputs").Append(dot)
                .Append(spec.Outputs).Append(spec.Outputs == 1 ? " output" : " outputs");
            if (definition != null)
            {
                int uses = DefinitionUsage.CountUsages(_workspace.Library, _workspace.RootCircuit, definition.Id);
                _builder.Append(dot).Append(uses == 0 ? "unused" : "used " + uses.ToString(CultureInfo.InvariantCulture) + "×");
            }

            _stats.text = _builder.ToString();

            BuildTable(component, spec.Title, int.MaxValue);

            _footer.text = component.Kind == ComponentKind.Custom
                ? "Double-click to open  \u00b7  right-click for more"
                : "Drag to place  \u00b7  right-click for more";

            // Keep the card on screen: drop the description first, then show only the first rows of the table.
            LayoutRebuilder.ForceRebuildLayoutImmediate(_rect);
            float limit = _canvas.rect.height - 16f;
            if (_rect.rect.height > limit && _description.gameObject.activeSelf)
            {
                _description.gameObject.SetActive(false);
                LayoutRebuilder.ForceRebuildLayoutImmediate(_rect);
            }

            if (_rect.rect.height > limit && ShownTableRows > ExcerptRows)
            {
                BuildTable(component, spec.Title, ExcerptRows);
                LayoutRebuilder.ForceRebuildLayoutImmediate(_rect);
            }

            Place();
        }

        private void DrawDiagram(ComponentRef component, LibraryEntrySpec spec)
        {
            VisualTheme theme = _ui.Theme;
            _usedPins = 0;
            _usedLabels = 0;
            _pinNames.Clear();
            string boundaryTitle = component.Kind == ComponentKind.InputBoundary ? "A"
                : component.Kind == ComponentKind.OutputBoundary ? "OUT" : null;
            GateGeometry geometry = _workspace.Geometry.ComputeDetached(component, boundaryTitle);
            _workspace.Catalog.TryGetSignature(component, out ComponentSignature signature);

            float available = Width - 2f * Padding;
            int maxPins = Mathf.Max(geometry.InputPins.Length, geometry.OutputPins.Length);
            float labelChars = Mathf.Max(LongestName(signature?.Inputs), LongestName(signature?.Outputs));
            bool labels = maxPins > 0 && maxPins <= 12;
            float labelWidth = labels ? Mathf.Min(70f, 7f * labelChars + 10f) : 0f;
            float stub = 9f;
            Vector2 size = geometry.Size;
            float scale = Mathf.Min(MaxScale, (DiagramHeight - 24f) / Mathf.Max(1f, size.y),
                (available - 2f * (labelWidth + stub) - 8f) / Mathf.Max(1f, size.x));
            scale = Mathf.Max(4f, scale);
            Vector2 bodySize = size * scale;
            _diagramLayout.preferredHeight = Mathf.Clamp(bodySize.y + 30f, 64f, DiagramHeight);

            bool custom = component.Kind == ComponentKind.Custom;
            bool boundary = component.IsUtility && component.Kind != ComponentKind.TriState && !component.IsWiring;
            _body.color = custom ? theme.CustomGateFill : boundary ? theme.BoundaryFill : theme.GateFill;
            _body.transform.GetChild(0).GetComponent<Image>().color = custom ? theme.CustomGateOutline : theme.GateOutline;
            _body.rectTransform.sizeDelta = bodySize;
            _body.rectTransform.anchoredPosition = Vector2.zero;
            _bodyTitle.text = string.IsNullOrEmpty(geometry.Title) ? spec.Title : geometry.Title;
            _bodyTitle.gameObject.SetActive(bodySize.x >= 18f);

            float fontSize = Mathf.Clamp(scale * 0.62f, 8f, 10.5f);
            Color pinColor = theme.TextMuted;
            for (int i = 0; i < geometry.InputPins.Length; i++)
            {
                string name = signature != null && i < signature.Inputs.Count ? PinName(signature.Inputs[i]) : string.Empty;
                AddPin(geometry.InputPins[i] * scale, -1f, stub, name, labels, labelWidth, fontSize, pinColor);
            }

            for (int i = 0; i < geometry.OutputPins.Length; i++)
            {
                string name = signature != null && i < signature.Outputs.Count ? PinName(signature.Outputs[i]) : string.Empty;
                AddPin(geometry.OutputPins[i] * scale, 1f, stub, name, labels, labelWidth, fontSize, pinColor);
            }

            for (int i = _usedPins; i < _pinPool.Count; i++)
            {
                _pinPool[i].gameObject.SetActive(false);
            }

            for (int i = _usedLabels; i < _labelPool.Count; i++)
            {
                _labelPool[i].gameObject.SetActive(false);
            }
        }

        private void AddPin(Vector2 position, float side, float stub, string name, bool labels, float labelWidth,
            float fontSize, Color color)
        {
            Image line = NextPin();
            line.sprite = null;
            RectTransform lineRect = line.rectTransform;
            lineRect.sizeDelta = new Vector2(stub, 1.6f);
            lineRect.anchoredPosition = new Vector2(position.x + side * stub * 0.5f, position.y);
            line.color = color;

            Image dot = NextPin();
            dot.sprite = RenderAssets.Circle;
            dot.rectTransform.sizeDelta = new Vector2(6f, 6f);
            dot.rectTransform.anchoredPosition = new Vector2(position.x + side * stub, position.y);
            dot.color = color;

            _pinNames.Add(name);
            if (!labels || string.IsNullOrEmpty(name))
            {
                return;
            }

            TextMeshProUGUI label = NextLabel();
            label.text = name;
            label.fontSize = fontSize;
            label.alignment = side < 0f ? TextAlignmentOptions.MidlineRight : TextAlignmentOptions.MidlineLeft;
            RectTransform rect = label.rectTransform;
            rect.pivot = new Vector2(side < 0f ? 1f : 0f, 0.5f);
            rect.sizeDelta = new Vector2(labelWidth, 18f);
            rect.anchoredPosition = new Vector2(position.x + side * (stub + 6f), position.y);
        }

        private Image NextPin()
        {
            if (_usedPins == _pinPool.Count)
            {
                Image image = _ui.Panel("Pin", _diagram, Color.white);
                image.raycastTarget = false;
                image.rectTransform.anchorMin = image.rectTransform.anchorMax = new Vector2(0.5f, 0.5f);
                image.rectTransform.pivot = new Vector2(0.5f, 0.5f);
                _pinPool.Add(image);
            }

            Image pin = _pinPool[_usedPins++];
            pin.gameObject.SetActive(true);
            return pin;
        }

        private TextMeshProUGUI NextLabel()
        {
            if (_usedLabels == _labelPool.Count)
            {
                TextMeshProUGUI text = _ui.Text("Label", _diagram, string.Empty, 9f, _ui.Theme.TextSecondary);
                text.rectTransform.anchorMin = text.rectTransform.anchorMax = new Vector2(0.5f, 0.5f);
                // A too-short rect with ellipsis overflow makes TMP drop the whole line; let labels overflow instead.
                text.overflowMode = TextOverflowModes.Overflow;
                _labelPool.Add(text);
            }

            TextMeshProUGUI label = _labelPool[_usedLabels++];
            label.gameObject.SetActive(true);
            return label;
        }

        private static string PinName(PortDescriptor port)
        {
            return port.IsBus ? port.Name + "[" + port.Width.ToString(CultureInfo.InvariantCulture) + "]" : port.Name;
        }

        private static int LongestName(IReadOnlyList<PortDescriptor> ports)
        {
            int longest = 0;
            if (ports == null)
            {
                return 0;
            }

            for (int i = 0; i < ports.Count; i++)
            {
                longest = Mathf.Max(longest, PinName(ports[i]).Length);
            }

            return longest;
        }

        /// <summary>
        /// Lays the table out inside the card: one block, or two side-by-side blocks for tall tables. The font shrinks
        /// (down to <see cref="TableMinFont"/>) to fit the width; output columns that still do not fit are summarised
        /// as "+N". At most <paramref name="maxRows"/> rows are drawn.
        /// </summary>
        private void BuildTable(ComponentRef component, string title, int maxRows)
        {
            TableRows = 0;
            ShownTableRows = 0;
            _table2.gameObject.SetActive(false);
            TableEntry entry = TableFor(component, title);
            float inner = TableInnerWidth;
            if (entry.Table == null)
            {
                bool show = !string.IsNullOrEmpty(entry.Reason);
                _tableBox.gameObject.SetActive(show);
                if (show)
                {
                    _table.enableWordWrapping = true;
                    _table.fontSize = 11f;
                    _table.text = "<color=#" + ColorUtility.ToHtmlStringRGB(_ui.Theme.TextMuted) + ">" + entry.Reason +
                        "</color>";
                    float height = _table.GetPreferredValues(_table.text, inner, 0f).y;
                    PlaceBlock(_table, 0f, inner, height);
                    _tableLayout.preferredHeight = height + 2f * TablePadY;
                }

                return;
            }

            TruthTableData table = entry.Table;
            TableRows = table.RowCount;
            int rows = Mathf.Min(table.RowCount, maxRows);
            ShownTableRows = rows;
            _tableBox.gameObject.SetActive(true);
            _table.enableWordWrapping = false;
            _table2.enableWordWrapping = false;
            // Many single-bit outputs read better as one bit string than as a column each at a tiny size.
            _packOutputs = false;
            float packAt = TableInnerWidth * 1.35f;
            if (Measure(Format(table, 0, Mathf.Min(rows, 2), int.MaxValue, null)).x > packAt)
            {
                _packOutputs = true;
            }

            int outputs = OutputGroupCount(table);
            float shrink = TableMinFont / TableMaxFont;

            // Tall tables: two blocks side by side when both fit at a readable size.
            if (rows == table.RowCount && rows > 8)
            {
                int half = (rows + 1) / 2;
                float blockWidth = (inner - TableGap) * 0.5f;
                string left = Format(table, 0, half, outputs, null);
                float leftWidth = Measure(left).x;
                if (leftWidth * shrink <= blockWidth)
                {
                    string right = Format(table, half, rows, outputs, null);
                    float size = FitFont(Mathf.Max(leftWidth, Measure(right).x), blockWidth);
                    _table.fontSize = size;
                    _table2.fontSize = size;
                    _table.text = left;
                    _table2.text = right;
                    float height = Mathf.Max(_table.GetPreferredValues(left).y, _table2.GetPreferredValues(right).y);
                    PlaceBlock(_table, 0f, blockWidth, height);
                    PlaceBlock(_table2, blockWidth + TableGap, blockWidth, height);
                    _table2.gameObject.SetActive(true);
                    _tableLayout.preferredHeight = height + 2f * TablePadY;
                    return;
                }
            }

            string note = rows < table.RowCount
                ? (table.RowCount - rows).ToString(CultureInfo.InvariantCulture) + " more rows in the truth table"
                : null;
            string text = Format(table, 0, rows, outputs, note);
            float width = Measure(text).x;
            while (outputs > 1 && width * shrink > inner)
            {
                outputs--;
                text = Format(table, 0, rows, outputs, note);
                width = Measure(text).x;
            }

            _table.fontSize = FitFont(width, inner);
            _table.text = text;
            float tableHeight = _table.GetPreferredValues(text).y;
            PlaceBlock(_table, 0f, inner, tableHeight);
            _tableLayout.preferredHeight = tableHeight + 2f * TablePadY;
        }

        /// <summary>Preferred size of <paramref name="text"/> at the largest table font.</summary>
        private Vector2 Measure(string text)
        {
            _table.fontSize = TableMaxFont;
            return _table.GetPreferredValues(text);
        }

        private static float FitFont(float widthAtMax, float available)
        {
            if (widthAtMax <= available || widthAtMax <= 0f)
            {
                return TableMaxFont;
            }

            return Mathf.Max(TableMinFont, Mathf.Floor(TableMaxFont * available / widthAtMax * 4f) / 4f);
        }

        private static void PlaceBlock(TextMeshProUGUI text, float x, float width, float height)
        {
            RectTransform rect = text.rectTransform;
            rect.anchoredPosition = new Vector2(TablePadX + x, -TablePadY);
            rect.sizeDelta = new Vector2(width, height);
        }

        private TableEntry TableFor(ComponentRef component, string title)
        {
            if (_tables.TryGetValue(component, out TableEntry cached))
            {
                return cached;
            }

            TableEntry entry = Generate(component, title);
            _tables[component] = entry;
            return entry;
        }

        private TableEntry Generate(ComponentRef component, string title)
        {
            if (component.IsUtility || _generator == null)
            {
                return default;
            }

            if (!_workspace.Catalog.TryGetSignature(component, out ComponentSignature signature))
            {
                return default;
            }

            int bits = 0;
            for (int i = 0; i < signature.Inputs.Count; i++)
            {
                bits += signature.Inputs[i].Width;
            }

            if (bits > MaxTableInputs)
            {
                return new TableEntry(null, null, bits + " input bits: open the truth table for all " +
                    TruthTableGenerator.FormatCount(TruthTableLimits.RowsFor(bits)) + " rows.");
            }

            CircuitDefinition target = TruthTableTargets.ForComponent(_workspace.Catalog, component, title);
            TruthTableGenerator generator = _generator();
            if (target == null || generator == null)
            {
                return default;
            }

            TruthTableJob job;
            try
            {
                job = generator.Generate(target);
            }
            catch (Exception exception)
            {
                return new TableEntry(null, null, exception.Message);
            }

            if (job.Status != TruthTableStatus.Completed || job.Table == null)
            {
                string reason = job.Plan?.FirstError ?? job.Error ?? "No truth table for this part.";
                return new TableEntry(null, null, FirstSentence(reason));
            }

            return new TableEntry(job.Table, null, null);
        }

        /// <summary>
        /// Table text for rows [<paramref name="start"/>, <paramref name="end"/>). Bits of a bus port are packed into one
        /// column (most significant first, e.g. <c>Y 0001</c>), the usual way to read multi-bit values and far narrower
        /// than one column per bit. Only the first <paramref name="outputs"/> output ports are shown (the rest
        /// summarised as "+N"); <paramref name="note"/> adds a muted line underneath.
        /// </summary>
        private string Format(TruthTableData table, int start, int end, int outputs, string note)
        {
            VisualTheme theme = _ui.Theme;
            string muted = ColorUtility.ToHtmlStringRGB(theme.TextMuted);
            string high = ColorUtility.ToHtmlStringRGB(theme.SignalColor(Signal.High));
            string border = ColorUtility.ToHtmlStringRGB(theme.PanelBorder);
            Group(table.Inputs, _inputGroups, false);
            Group(table.Outputs, _outputGroups, _packOutputs);
            int shownOutputs = Mathf.Min(outputs, _outputGroups.Count);

            _builder.Clear();
            _builder.Append("<mspace=0.62em>");
            _builder.Append("<color=#").Append(muted).Append('>');
            for (int g = 0; g < _inputGroups.Count; g++)
            {
                Cell(_inputGroups[g].Name, _inputGroups[g].Width);
            }

            _builder.Append("<color=#").Append(border).Append(">\u2502 </color>");
            for (int g = 0; g < shownOutputs; g++)
            {
                Cell(_outputGroups[g].Name, _outputGroups[g].Width);
            }

            if (shownOutputs < _outputGroups.Count)
            {
                _builder.Append('+').Append(_outputGroups.Count - shownOutputs);
            }

            _builder.Append("</color>");
            for (int row = start; row < end; row++)
            {
                _builder.Append('\n');
                for (int g = 0; g < _inputGroups.Count; g++)
                {
                    ColumnGroup group = _inputGroups[g];
                    for (int b = 0; b < group.Count; b++)
                    {
                        _builder.Append(TruthTableData.Symbol(table.GetInput(row, group.First + b)));
                    }

                    _builder.Append(' ', group.Width - group.Count);
                }

                _builder.Append("<color=#").Append(border).Append(">\u2502 </color>");
                for (int g = 0; g < shownOutputs; g++)
                {
                    ColumnGroup group = _outputGroups[g];
                    for (int b = 0; b < group.Count; b++)
                    {
                        Signal signal = table.GetOutput(row, group.First + b);
                        _builder.Append("<color=#").Append(signal == Signal.High ? high : muted).Append('>')
                            .Append(TruthTableData.Symbol(signal)).Append("</color>");
                    }

                    _builder.Append(' ', group.Width - group.Count);
                }
            }

            _builder.Append("</mspace>");
            if (!string.IsNullOrEmpty(note))
            {
                _builder.Append("\n<size=88%><color=#").Append(muted).Append(">\u2026 ").Append(note).Append("</color></size>");
            }

            return _builder.ToString();
        }

        /// <summary>Output port count of <paramref name="table"/> (bus bits grouped).</summary>
        private int OutputGroupCount(TruthTableData table)
        {
            Group(table.Outputs, _outputGroups, _packOutputs);
            return _outputGroups.Count;
        }

        /// <summary>Groups consecutive bit columns of the same port; a column is as wide as its name or its bits.</summary>
        private static void Group(IReadOnlyList<TruthTableColumn> columns, List<ColumnGroup> groups, bool pack)
        {
            groups.Clear();
            if (pack && columns.Count > 1)
            {
                groups.Add(new ColumnGroup(0, columns.Count, RangeName(columns[0].Name, columns[columns.Count - 1].Name)));
                return;
            }

            for (int c = 0; c < columns.Count; c++)
            {
                if (groups.Count > 0 && columns[groups[groups.Count - 1].First].Port == columns[c].Port)
                {
                    ColumnGroup last = groups[groups.Count - 1];
                    groups[groups.Count - 1] = new ColumnGroup(last.First, last.Count + 1, last.Name);
                    continue;
                }

                string name = columns[c].Name;
                int bracket = name.IndexOf('[');
                if (bracket > 0)
                {
                    name = name.Substring(0, bracket);
                }

                groups.Add(new ColumnGroup(c, 1, name.Length > 6 ? name.Substring(0, 6) : name));
            }
        }

        /// <summary>Header for a packed column: "Y0-15" for Y0..Y15, otherwise the first name and an ellipsis.</summary>
        private static string RangeName(string first, string last)
        {
            int prefix = 0;
            while (prefix < first.Length && prefix < last.Length && first[prefix] == last[prefix] &&
                   !char.IsDigit(first[prefix]))
            {
                prefix++;
            }

            string a = first.Substring(prefix);
            string b = last.Substring(prefix);
            if (prefix > 0 && a.Length > 0 && b.Length > 0 && char.IsDigit(a[0]) && char.IsDigit(b[0]))
            {
                return first.Substring(0, prefix) + a + "-" + b;
            }

            return (first.Length > 5 ? first.Substring(0, 5) : first) + "…";
        }

        private readonly struct ColumnGroup
        {
            public ColumnGroup(int first, int count, string name)
            {
                First = first;
                Count = count;
                Name = name;
            }

            public int First { get; }

            public int Count { get; }

            public string Name { get; }

            /// <summary>Characters including one space of separation.</summary>
            public int Width => Mathf.Max(Name.Length, Count) + 1;
        }

        private void Cell(string text, int width)
        {
            if (text.Length > width - 1)
            {
                text = text.Substring(0, width - 1);
            }

            if (text.IndexOf('<') >= 0)
            {
                _builder.Append("<noparse>").Append(text).Append("</noparse>");
            }
            else
            {
                _builder.Append(text);
            }

            _builder.Append(' ', width - text.Length);
        }

        private static string FirstSentence(string text)
        {
            int end = text.IndexOf(". ", StringComparison.Ordinal);
            return end > 0 ? text.Substring(0, end + 1) : text;
        }

        private static readonly Vector3[] Corners = new Vector3[4];

        /// <summary>To the right of the library, top aligned with the hovered row, clamped to the screen.</summary>
        private void Place()
        {
            RectTransform row = (RectTransform)_source.transform;
            row.GetWorldCorners(Corners);
            float rowTop = ToCanvas(Corners[1]).y;
            float x = ToCanvas(Corners[2]).x + 10f;
            if (_anchor != null)
            {
                _anchor.GetWorldCorners(Corners);
                x = ToCanvas(Corners[2]).x + 10f;
            }

            Vector2 canvas = _canvas.rect.size;
            float height = _rect.rect.height;
            float y = Mathf.Clamp(rowTop + 8f, height + 8f, canvas.y - 8f);
            x = Mathf.Min(x, canvas.x - Width - 8f);
            _rect.anchoredPosition = new Vector2(x, y);
        }

        private Vector2 ToCanvas(Vector3 world)
        {
            Vector2 screen = RectTransformUtility.WorldToScreenPoint(null, world);
            RectTransformUtility.ScreenPointToLocalPointInRectangle(_canvas, screen, null, out Vector2 local);
            return local + _canvas.rect.size * _canvas.pivot;
        }

        private void OnDestroy()
        {
            if (_group != null)
            {
                _group.DOKill();
            }
        }

