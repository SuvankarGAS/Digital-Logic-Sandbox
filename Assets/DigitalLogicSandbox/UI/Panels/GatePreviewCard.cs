    /// <summary>
    /// Rich hover card for gate library entries, shown beside the library after a short rest on a row: the gate drawn
    /// with its named pins (same layout maths as the workspace, <see cref="GateLayout"/>), description, version and
    /// usage, and for small combinational parts a live truth table generated by the real simulation engine in an
    /// isolated context. Tables are cached per component (custom gates per version) and cleared when the library
    /// changes. Pins, labels and the table text are pooled and reused across hovers.
    /// </summary>
    public sealed class GatePreviewCard : MonoBehaviour
    {
        /// <summary>Seconds the pointer must rest on a row before the card appears.</summary>
        public const float Delay = 0.45f;

        /// <summary>Largest table shown in the card (input bits).</summary>
        public const int MaxTableInputs = 4;

