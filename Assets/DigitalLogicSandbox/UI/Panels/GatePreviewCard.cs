        private const float DiagramHeight = 118f;
        private const float MaxScale = 20f;
        private const float TableGap = 14f;
        private const float TablePadX = 10f;
        private const float TablePadY = 6f;
        private const float TableMaxFont = 11.5f;
        private const float TableMinFont = 7.5f;

        /// <summary>Rows kept when the card would not fit on screen with the whole table.</summary>
        public const int ExcerptRows = 4;

        private readonly List<Image> _pinPool = new List<Image>();
        private readonly List<TextMeshProUGUI> _labelPool = new List<TextMeshProUGUI>();
        private readonly Dictionary<ComponentRef, TableEntry> _tables = new Dictionary<ComponentRef, TableEntry>();
        private readonly List<string> _pinNames = new List<string>();
        private readonly StringBuilder _builder = new StringBuilder(512);
        private readonly List<ColumnGroup> _inputGroups = new List<ColumnGroup>();
        private readonly List<ColumnGroup> _outputGroups = new List<ColumnGroup>();

        /// <summary>Pack every output bit into one column (many single-bit outputs, e.g. a 4-to-16 decoder).</summary>
        private bool _packOutputs;

        private UiFactory _ui;
        private WorkspaceController _workspace;
        private Func<TruthTableGenerator> _generator;
        private RectTransform _rect;
        private RectTransform _canvas;
        private CanvasGroup _group;
        private TextMeshProUGUI _title;
        private TextMeshProUGUI _badge;
        private Image _badgeBack;
        private TextMeshProUGUI _subtitle;
        private RectTransform _diagram;
        private LayoutElement _diagramLayout;
        private Image _body;
        private TextMeshProUGUI _bodyTitle;
        private TextMeshProUGUI _description;
        private TextMeshProUGUI _stats;
        private RectTransform _tableBox;
        private TextMeshProUGUI _table;
        private TextMeshProUGUI _table2;
        private LayoutElement _tableLayout;
        private TextMeshProUGUI _footer;
        private LibraryItemView _source;
        private RectTransform _anchor;
        private float _showAt;
        private bool _built;
        private int _usedPins;
        private int _usedLabels;

        /// <summary>True once the card has (started to) fade in.</summary>
        public bool IsVisible => gameObject.activeSelf && _built && Time.unscaledTime >= _showAt;

        public LibraryItemView Source => _source;

        public string TitleText => _title.text;

        /// <summary>Pin names drawn in the diagram (inputs then outputs).</summary>
        public IReadOnlyList<string> PinNames => _pinNames;

        /// <summary>Rows of the component's truth table (0 when none is shown).</summary>
        public int TableRows { get; private set; }

        /// <summary>Rows actually drawn (fewer than <see cref="TableRows"/> when an excerpt keeps the card on screen).</summary>
        public int ShownTableRows { get; private set; }

        /// <summary>True when the table is drawn as two side-by-side blocks.</summary>
        public bool TableSplit => _table2 != null && _table2.gameObject.activeSelf;

        /// <summary>The table area (layout tests: it must stay inside the card).</summary>
        public RectTransform TableArea => _tableBox;

        /// <summary>Inner width available to the table.</summary>
        public static float TableInnerWidth => Width - 2f * Padding - 2f * TablePadX;

        /// <summary>The table text (or the reason none is shown).</summary>
        public string TableText => _table.text;

        public static GatePreviewCard Create(Transform parent, UiFactory ui, WorkspaceController workspace,
            Func<TruthTableGenerator> generator)
        {
            Image card = ui.Card("Gate Preview", parent, ui.Theme.PanelHeader, radius: 12f);
            card.raycastTarget = false;
            var view = card.gameObject.AddComponent<GatePreviewCard>();
            view._ui = ui;
            view._workspace = workspace;
            view._generator = generator;
            view._rect = card.rectTransform;
            view._canvas = (RectTransform)parent;
            view._rect.anchorMin = view._rect.anchorMax = Vector2.zero;
            view._rect.pivot = new Vector2(0f, 1f);
            view._rect.sizeDelta = new Vector2(Width, 200f);
            view._group = card.gameObject.AddComponent<CanvasGroup>();
            view._group.blocksRaycasts = false;
            view._group.interactable = false;

            var layout = card.gameObject.AddComponent<VerticalLayoutGroup>();
            int pad = (int)Padding;
            layout.padding = new RectOffset(pad, pad, 12, 12);
            layout.spacing = 6f;
            layout.childControlWidth = true;
            layout.childControlHeight = true;
            layout.childForceExpandWidth = true;
            layout.childForceExpandHeight = false;
            card.gameObject.AddComponent<ContentSizeFitter>().verticalFit = ContentSizeFitter.FitMode.PreferredSize;
            view.Build();
            card.gameObject.SetActive(false);
            return view;
        }

